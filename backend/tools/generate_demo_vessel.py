"""Generate a SYNTHETIC MR2 product tanker model for the demo.

Every number here comes from simplified box-hull formulas, not from a real ship.
Never use this data for an actual loading decision.

Run:  python tools/generate_demo_vessel.py
Writes: data/vessels/demo_mr2.json
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.schemas import LayoutTank, VesselLayout  # noqa: E402
from app.vessel_builder import build_vessel  # noqa: E402

LBP, B, D = 176.0, 32.2, 19.1
T_MAX = 12.2
DB, DS = 2.0, 2.0  # double bottom height, double side width


def demo_layout() -> VesselLayout:
    tanks = []
    # 6 pairs of cargo tanks between x = 33 and x = 153, centreline bulkhead
    bounds = [33 + 20 * i for i in range(7)]
    for n in range(6):
        no = 6 - n  # COT1 is forward
        for side in ("P", "S"):
            tanks.append(LayoutTank(id=f"COT{no}{side}", name=f"Cargo tank {no} {'port' if side == 'P' else 'starboard'}",
                                    type="cargo", side=side, xAft=bounds[n], xFwd=bounds[n + 1],
                                    shapeFactor=0.90 if no in (1, 6) else 0.97, coating="epoxy",
                                    lineId=f"L{(no + 1) // 2}"))
    for side in ("P", "S"):
        tanks.append(LayoutTank(id=f"SLOP{side}", name=f"Slop tank {'port' if side == 'P' else 'starboard'}",
                                type="slop", side=side, xAft=29, xFwd=33, shapeFactor=0.95,
                                coating="epoxy", lineId="L4"))
    # ballast: double hull wing + bottom, modelled as one box per side per cargo tank pair
    for n in range(6):
        no = 6 - n
        for side in ("P", "S"):
            tanks.append(LayoutTank(id=f"WBT{no}{side}", name=f"Water ballast {no} {'port' if side == 'P' else 'starboard'}",
                                    type="ballast", side=side, xAft=bounds[n], xFwd=bounds[n + 1]))
    tanks.append(LayoutTank(id="FPT", name="Forepeak tank", type="ballast", side="C", xAft=160, xFwd=172,
                            yIn=-6, yOut=6, zBottom=0, zTop=12, shapeFactor=0.55))
    for side in ("P", "S"):
        tanks.append(LayoutTank(id=f"FO{side}", name=f"Fuel oil {'port' if side == 'P' else 'starboard'}",
                                type="fuel_oil", side=side, xAft=18, xFwd=26, yIn=6, yOut=12,
                                zBottom=DB, zTop=14, shapeFactor=0.95))
    tanks.append(LayoutTank(id="DO", name="Diesel oil", type="diesel_oil", side="C", xAft=14, xFwd=18,
                            yIn=-3, yOut=3, zBottom=DB, zTop=10, shapeFactor=0.95))
    tanks.append(LayoutTank(id="FW", name="Fresh water", type="fresh_water", side="C", xAft=2, xFwd=8,
                            yIn=-5, yOut=5, zBottom=8, zTop=14, shapeFactor=0.95))
    return VesselLayout(name="MT Demo Fjord", sizeClass="MR2", lbp=LBP, breadth=B, depth=D,
                        summerDraught=T_MAX, doubleBottom=DB, doubleSide=DS, tanks=tanks)


def build() -> dict:
    return build_vessel(
        demo_layout(), "demo_mr2",
        source={"origin": "synthetic",
                "notes": "Fictional MR2 generated by tools/generate_demo_vessel.py. Not a real ship."},
        lightship={"weight": 10400, "lcg": 80.5, "vcg": 11.2, "tcg": 0.0,
                   "distribution": [
                       {"xAft": 0, "xFwd": 30, "weight": 3400},
                       {"xAft": 30, "xFwd": 152, "weight": 5900},
                       {"xAft": 152, "xFwd": 176, "weight": 1100}]},
        cargo_system={
            "pumps": [{"id": f"CP{i}", "ratedM3h": 550} for i in range(1, 5)],
            "lines": [
                {"id": "L1", "pumpId": "CP1", "tankIds": ["COT1P", "COT1S", "COT2P", "COT2S"]},
                {"id": "L2", "pumpId": "CP2", "tankIds": ["COT3P", "COT3S", "COT4P", "COT4S"]},
                {"id": "L3", "pumpId": "CP3", "tankIds": ["COT5P", "COT5S", "COT6P", "COT6S"]},
                {"id": "L4", "pumpId": "CP4", "tankIds": ["SLOPP", "SLOPS"]}],
            "crossovers": [
                {"id": "X12", "lineIds": ["L1", "L2"], "valveCount": 2},
                {"id": "X23", "lineIds": ["L2", "L3"], "valveCount": 2}],
            "maxSegregations": 3},
        constants=[{"name": "Crew, stores and provisions", "weight": 300,
                    "lcg": 20.0, "vcg": 15.0, "tcg": 0.0}],
    )


if __name__ == "__main__":
    out = Path(__file__).resolve().parents[1] / "data" / "vessels" / "demo_mr2.json"
    out.write_text(json.dumps(build(), indent=2))
    print(f"Wrote {out}")
